local function char_at(text, idx)
	return string.sub(text, idx, idx)
end

local function render_char(char, x, y, size)
	local ascii = FONT[char]
	if ascii == nil then
		ascii = FONT[UNKNOWN_CHAR]
	end
	for i, row in ipairs(ascii) do
		local ny = y + (i - 1) * size
		for j, col in ipairs(row) do
			if col == 1 then
				local nx = x + (j - 1) * size
				love.graphics.rectangle("fill", nx, ny, size, size)
			end
		end
	end
end

function M.render_text(text, x, y, size)
	-- TODO: handle new lines
	text = string.upper(text)
	for c = 1, #text do
		local char = char_at(text, c)
		render_char(char, x, y, size)
		x = x + 6 * size
	end
end

function M.text_width(text, size)
	local n_chars = string.len(text)
	local chars_width = n_chars * 5 * size
	if n_chars < 2 then
		return chars_width
	end
	return chars_width + (n_chars - 1) * size
end

function M.text_height(text, size)
	-- TODO: handle new lines
	return size * 7
end

